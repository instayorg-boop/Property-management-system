import { Fragment } from "react";

// Renders an HTML replica of the generated report, styled to match the PDF design spec, so the
// landlord sees exactly what they're about to download before committing to it. Built from the
// same `data` object generate-report used to build the actual file (see the edge function's
// response shape) — never re-fetched, so the preview and the download can't show different numbers.

type IncomeExpensesData = {
  rentCollected: number;
  groups: { category: string; items: { name: string; amount: number; count?: number }[] }[];
  totalExpenses: number;
  net: number;
  months?: { month: string; label: string; rent: number; expenses: number; net: number }[];
  periodLabel?: string;
};

type OccupancyData = {
  rows: { roomType: string; rooms: number; bedsTotal: number; bedsOccupied: number }[];
  totalRooms: number;
  totalBeds: number;
  totalOccupied: number;
  vacant: number;
  occupancyPct: number;
};

type OverdueRentData = {
  rows: { tenant: string; room: string; daysOverdue: number; owed: number; emergencyContact: string | null }[];
  totalOwed: number;
};

export type GenerateReportResult = {
  ok: true;
  url: string;
  filePath: string;
  fileName: string;
  reportType: "income_vs_expenses" | "occupancy" | "overdue_rent";
  dateFrom: string;
  dateTo: string;
  createdOn: string;
  property: { name: string | null; location: string | null; logoUrl: string | null };
  data: IncomeExpensesData | OccupancyData | OverdueRentData;
};

const REPORT_TITLE: Record<GenerateReportResult["reportType"], string> = {
  income_vs_expenses: "Income vs expenses",
  occupancy: "Occupancy rate",
  overdue_rent: "Overdue rent",
};

const REPORT_AUDIENCE: Record<GenerateReportResult["reportType"], string> = {
  income_vs_expenses: "Landlord / Accountant",
  occupancy: "Property Manager / Investor",
  overdue_rent: "Property Manager / Operations",
};

function formatDMY(iso: string): string {
  const d = new Date(`${iso}T00:00:00`);
  return `${String(d.getDate()).padStart(2, "0")}/${String(d.getMonth() + 1).padStart(2, "0")}/${d.getFullYear()}`;
}

function monthYearLabel(iso: string): string {
  return new Date(`${iso}T00:00:00`).toLocaleDateString("en-GB", { month: "long", year: "numeric" });
}

function kwacha(amount: number): string {
  const hasCents = Math.abs(amount % 1) > 0.001;
  const n = hasCents ? amount.toFixed(2) : Math.round(amount).toString();
  const [whole, cents] = n.split(".");
  return `K${whole.replace(/\B(?=(\d{3})+(?!\d))/g, ",")}${cents ? `.${cents}` : ""}`;
}

function ReportHeader({ result, periodLine }: { result: GenerateReportResult; periodLine: string }) {
  return (
    <div className="flex items-start justify-between gap-6 border-b border-[#e5e4e0] py-8">
      <div>
        <p className="text-[13px] text-[#777]">Report generated by</p>
        <div className="mt-2 flex items-center gap-2.5">
          {result.property.logoUrl ? (
            <img src={result.property.logoUrl} alt="" className="h-9 w-9 rounded-lg object-cover" />
          ) : (
            <span className="flex h-9 w-9 items-center justify-center rounded-lg bg-[#14532d] text-[13px] font-bold text-white">IPM</span>
          )}
          <p className="text-lg font-bold tracking-[-0.03em] text-[#1a1a1a]">Instay Manage</p>
        </div>
        <h1 className="font-display mt-4 text-2xl font-bold text-[#1a1a1a]">{REPORT_TITLE[result.reportType]}</h1>
        <p className="mt-3 text-sm text-[#1a1a1a]">Report created on: {result.createdOn}</p>
        <p className="mt-1 text-sm text-[#1a1a1a]">{periodLine}</p>
        <p className="mt-1 text-sm text-[#1a1a1a]">Prepared for: {REPORT_AUDIENCE[result.reportType]}</p>
      </div>
      <div className="w-[190px] shrink-0 rounded-md bg-[#faf9f7] px-3 py-2.5 text-[11px]">
        <p className="font-bold text-[#1a1a1a]">{result.property.name || "[Property name]"}</p>
        <p className="mt-0.5 text-[#777]">{result.property.location || "[Property location]"}</p>
      </div>
    </div>
  );
}

function IncomeExpensesTable({ data, dateFrom }: { data: IncomeExpensesData; dateFrom: string }) {
  const period = data.periodLabel ?? monthYearLabel(dateFrom);
  const cell = "border border-[#8a8a8a] px-2.5 py-2";
  return (
    <div className="space-y-6">
      <div className="grid grid-cols-1 gap-3 sm:grid-cols-3">
        <div className="rounded-md bg-[#e3f1e7] p-4 text-[#14532d]">
          <p className="text-xs">Rent collected</p>
          <p className="mt-1 text-xl font-bold sm:text-2xl">{kwacha(data.rentCollected)}</p>
        </div>
        <div className="rounded-md bg-[#fbe9e3] p-4 text-[#9a3412]">
          <p className="text-xs">Expenses</p>
          <p className="mt-1 text-xl font-bold sm:text-2xl">{kwacha(data.totalExpenses)}</p>
        </div>
        <div className="rounded-md bg-[#14532d] p-4 text-white">
          <p className="text-xs">Net income</p>
          <p className="mt-1 text-xl font-bold sm:text-2xl">{kwacha(data.net)}</p>
        </div>
      </div>

      {data.months && data.months.length > 1 && (
        <div>
          <p className="mb-2 text-[15px] font-bold text-[#1a1a1a]">Month by month</p>
          <table className="w-full border-collapse text-[13px]">
            <thead>
              <tr className="bg-[#faf9f7] text-left">
                <th className={`${cell} font-bold`}>Month</th>
                <th className={`${cell} text-right font-bold`}>Rent collected</th>
                <th className={`${cell} text-right font-bold`}>Expenses</th>
                <th className={`${cell} text-right font-bold`}>Net</th>
              </tr>
            </thead>
            <tbody>
              {data.months.map((m) => (
                <tr key={m.month}>
                  <td className={cell}>{m.label}</td>
                  <td className={`${cell} text-right`}>{kwacha(m.rent)}</td>
                  <td className={`${cell} text-right`}>{kwacha(m.expenses)}</td>
                  <td className={`${cell} text-right ${m.net < 0 ? "text-[#9a3412]" : ""}`}>{kwacha(m.net)}</td>
                </tr>
              ))}
              <tr className="bg-[#faf9f7] font-bold">
                <td className={cell}>Total</td>
                <td className={`${cell} text-right`}>{kwacha(data.rentCollected)}</td>
                <td className={`${cell} text-right`}>{kwacha(data.totalExpenses)}</td>
                <td className={`${cell} text-right`}>{kwacha(data.net)}</td>
              </tr>
            </tbody>
          </table>
        </div>
      )}

      <div>
        <p className="mb-2 text-[15px] font-bold text-[#1a1a1a]">Breakdown</p>
        <table className="w-full border-collapse text-[13px]">
          <thead>
            <tr className="bg-[#faf9f7] text-left">
              <th className={`w-[50%] ${cell} font-bold`}>Item</th>
              <th className={`${cell} font-bold`}>Category</th>
              <th className={`${cell} text-right font-bold`}>Amount</th>
            </tr>
          </thead>
          <tbody>
            <tr className="bg-[#e3f1e7] font-bold text-[#14532d]">
              <td className={cell}>Rent collected</td>
              <td className={cell}>Income</td>
              <td className={`${cell} text-right`}>{kwacha(data.rentCollected)}</td>
            </tr>
            {data.groups.length === 0 && (
              <tr>
                <td className={`${cell} text-[#777]`} colSpan={3}>
                  No expenses logged in this period.
                </td>
              </tr>
            )}
            {data.groups.map((group) => {
              const subtotal = group.items.reduce((s, i) => s + i.amount, 0);
              return (
                <Fragment key={group.category}>
                  {group.items.map((item, i) => (
                    <tr key={`${group.category}-${item.name}-${i}`}>
                      <td className={cell}>
                        {item.name}
                        {item.count && item.count > 1 ? <span className="text-[#777]"> ({item.count} payments)</span> : null}
                      </td>
                      <td className={`${cell} text-[#777]`}>{i === 0 ? group.category : ""}</td>
                      <td className={`${cell} text-right`}>{kwacha(item.amount)}</td>
                    </tr>
                  ))}
                  <tr className="bg-[#faf9f7] font-bold">
                    <td className={cell} colSpan={2}>
                      {group.category} subtotal
                    </td>
                    <td className={`${cell} text-right`}>{kwacha(subtotal)}</td>
                  </tr>
                </Fragment>
              );
            })}
            <tr className="bg-[#fbe9e3] font-bold text-[#9a3412]">
              <td className={cell}>Total expenses</td>
              <td className={cell}>Expenses</td>
              <td className={`${cell} text-right`}>{kwacha(data.totalExpenses)}</td>
            </tr>
            <tr className="bg-[#14532d] font-bold text-white">
              <td className={cell}>Net for {period}</td>
              <td className={cell}>Net income</td>
              <td className={`${cell} text-right`}>{kwacha(data.net)}</td>
            </tr>
          </tbody>
        </table>
      </div>
    </div>
  );
}

function OccupancyView({ data }: { data: OccupancyData }) {
  return (
    <>
      <div className="grid grid-cols-1 gap-3 sm:grid-cols-3">
        <div className="rounded-md border border-[#b7d9c1] bg-[#e3f1e7] px-4 py-3.5">
          <p className="text-xs text-[#14532d]">Occupied beds</p>
          <p className="mt-1 text-xl font-bold sm:text-[26px] text-[#14532d]">
            {data.totalOccupied} / {data.totalBeds}
          </p>
        </div>
        <div className="rounded-md border border-[#ecd0a4] bg-[#fdf0dc] px-4 py-3.5">
          <p className="text-xs text-[#8a4b06]">Vacant beds</p>
          <p className="mt-1 text-xl font-bold sm:text-[26px] text-[#8a4b06]">{data.vacant}</p>
        </div>
        <div className="rounded-md bg-[#14532d] px-4 py-3.5">
          <p className="text-xs text-white/80">Occupancy rate</p>
          <p className="mt-1 text-[26px] font-bold text-white">{data.occupancyPct}%</p>
        </div>
      </div>

      <table className="mt-5 w-full border-collapse text-[13px]">
        <thead>
          <tr className="bg-[#faf9f7] text-left">
            <th className="border border-[#8a8a8a] px-2.5 py-2 font-bold">Room type</th>
            <th className="border border-[#8a8a8a] px-2.5 py-2 text-right font-bold">Rooms</th>
            <th className="border border-[#8a8a8a] px-2.5 py-2 text-right font-bold">Beds occupied</th>
            <th className="border border-[#8a8a8a] px-2.5 py-2 font-bold">Occupancy</th>
          </tr>
        </thead>
        <tbody>
          {data.rows.length === 0 && (
            <tr>
              <td className="border border-[#8a8a8a] px-2.5 py-2 text-[#777]" colSpan={4}>
                No rooms have been added yet.
              </td>
            </tr>
          )}
          {data.rows.map((r) => {
            const pct = r.bedsTotal > 0 ? Math.round((r.bedsOccupied / r.bedsTotal) * 100) : 0;
            return (
              <tr key={r.roomType}>
                <td className="border border-[#8a8a8a] px-2.5 py-2">{r.roomType}</td>
                <td className="border border-[#8a8a8a] px-2.5 py-2 text-right">{r.rooms}</td>
                <td className="border border-[#8a8a8a] px-2.5 py-2 text-right">
                  {r.bedsOccupied} / {r.bedsTotal}
                </td>
                <td className="border border-[#8a8a8a] px-2.5 py-2">
                  <div className="flex items-center gap-2">
                    <div className="h-2 w-[130px] rounded-full bg-[#e6e4df]">
                      <div className="h-2 rounded-full bg-[#14532d]" style={{ width: `${pct}%` }} />
                    </div>
                    <span>{pct}%</span>
                  </div>
                </td>
              </tr>
            );
          })}
          <tr className="bg-[#faf9f7] font-bold">
            <td className="border border-[#8a8a8a] px-2.5 py-2">Total</td>
            <td className="border border-[#8a8a8a] px-2.5 py-2 text-right">{data.totalRooms}</td>
            <td className="border border-[#8a8a8a] px-2.5 py-2 text-right">
              {data.totalOccupied} / {data.totalBeds}
            </td>
            <td className="border border-[#8a8a8a] px-2.5 py-2">
              <div className="flex items-center gap-2">
                <div className="h-2 w-[130px] rounded-full bg-[#e6e4df]">
                  <div className="h-2 rounded-full bg-[#14532d]" style={{ width: `${data.occupancyPct}%` }} />
                </div>
                <span>{data.occupancyPct}%</span>
              </div>
            </td>
          </tr>
        </tbody>
      </table>
    </>
  );
}

function OverdueRentView({ data }: { data: OverdueRentData }) {
  return (
    <>
      <div className="grid grid-cols-2 gap-3">
        <div className="rounded-md bg-[#faf9f7] px-4 py-3.5">
          <p className="text-xs text-[#1a1a1a]">Tenants behind on rent</p>
          <p className="mt-1 text-[26px] font-bold text-[#1a1a1a]">{data.rows.length}</p>
        </div>
        <div className="rounded-md bg-[#9a3412] px-4 py-3.5">
          <p className="text-xs text-white/80">Total owed</p>
          <p className="mt-1 text-[26px] font-bold text-white">{kwacha(data.totalOwed)}</p>
        </div>
      </div>

      <table className="mt-5 w-full border-collapse text-[13px]">
        <thead>
          <tr className="bg-[#faf9f7] text-left">
            <th className="border border-[#8a8a8a] px-2.5 py-2 font-bold">Tenant</th>
            <th className="border border-[#8a8a8a] px-2.5 py-2 font-bold">Room</th>
            <th className="border border-[#8a8a8a] px-2.5 py-2 text-right font-bold">Days overdue</th>
            <th className="border border-[#8a8a8a] px-2.5 py-2 text-right font-bold">Owed</th>
            <th className="border border-[#8a8a8a] px-2.5 py-2 font-bold">Emergency contact (parent / guardian)</th>
          </tr>
        </thead>
        <tbody>
          {data.rows.length === 0 && (
            <tr>
              <td className="border border-[#8a8a8a] px-2.5 py-2 text-[#777]" colSpan={5}>
                No tenants are behind on rent.
              </td>
            </tr>
          )}
          {data.rows.map((r, i) => (
            <tr key={i}>
              <td className="border border-[#8a8a8a] px-2.5 py-2">{r.tenant}</td>
              <td className="border border-[#8a8a8a] px-2.5 py-2">{r.room}</td>
              <td className="border border-[#8a8a8a] px-2.5 py-2 text-right">
                <span className="rounded-full bg-[#fbe9e3] px-2 py-0.5 text-xs font-bold text-[#9a3412]">{r.daysOverdue}d</span>
              </td>
              <td className="border border-[#8a8a8a] px-2.5 py-2 text-right">{kwacha(r.owed)}</td>
              <td className="border border-[#8a8a8a] px-2.5 py-2">
                {r.emergencyContact || <span className="text-[#777]">Not provided</span>}
              </td>
            </tr>
          ))}
          {data.rows.length > 0 && (
            <tr className="bg-[#fbe9e3] font-bold text-[#9a3412]">
              <td className="border border-[#8a8a8a] px-2.5 py-2" colSpan={3}>
                Total owed
              </td>
              <td className="border border-[#8a8a8a] px-2.5 py-2 text-right">{kwacha(data.totalOwed)}</td>
              <td className="border border-[#8a8a8a] px-2.5 py-2" />
            </tr>
          )}
        </tbody>
      </table>
    </>
  );
}

export default function ReportPreview({ result }: { result: GenerateReportResult }) {
  const periodLine =
    result.reportType === "income_vs_expenses"
      ? `Time Period: ${(result.data as IncomeExpensesData).periodLabel ?? monthYearLabel(result.dateFrom)} (${formatDMY(result.dateFrom)} to ${formatDMY(result.dateTo)})`
      : `As at: ${formatDMY(result.dateTo)}`;

  return (
    <div className="overflow-hidden  ">
      <ReportHeader result={result} periodLine={periodLine} />
      <div className="">
        {result.reportType === "income_vs_expenses" && (
          <IncomeExpensesTable data={result.data as IncomeExpensesData} dateFrom={result.dateFrom} />
        )}
        {result.reportType === "occupancy" && <OccupancyView data={result.data as OccupancyData} />}
        {result.reportType === "overdue_rent" && <OverdueRentView data={result.data as OverdueRentData} />}
      </div>
    </div>
  );
}
